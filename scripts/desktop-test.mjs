import {_electron as electron} from 'playwright';
import assert from 'node:assert/strict';
import {mkdtemp, readFile, writeFile, mkdir, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {freshState} from '../extension/core.js';
const temp=await mkdtemp(join(tmpdir(),'hackertube-e2e-'));
const results=[];let app;
const passed=name=>{results.push(name);console.log('✓ '+name);};
async function launch(){
  app=await electron.launch({...(process.env.HACKERTUBE_TEST_EXECUTABLE?{executablePath:process.env.HACKERTUBE_TEST_EXECUTABLE,args:[]}:{args:['.']}),cwd:process.cwd(),env:{...process.env,HACKERTUBE_USER_DATA:join(temp,'profile')},timeout:45000});
  const page=await app.firstWindow();
  await page.locator('.video-card').first().waitFor({timeout:30000});
  await app.evaluate(({session})=>session.defaultSession.enableNetworkEmulation({offline:true}));
  return page;
}
try {
  let page=await launch();
  assert.equal(await page.locator('#total-count').innerText(),'6,454');
  assert.equal(await page.locator('.video-card').count(),24);
  assert.match(await page.locator('#edition-label').innerText(),/DESKTOP/);
  passed('Bundled catalog and desktop edition render');
  const security=await app.evaluate(({BrowserWindow})=>{const p=BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences();return {sandbox:p.sandbox,contextIsolation:p.contextIsolation,nodeIntegration:p.nodeIntegration,webSecurity:p.webSecurity};});
  assert.deepEqual(security,{sandbox:true,contextIsolation:true,nodeIntegration:false,webSecurity:true});
  assert.deepEqual(await page.evaluate(()=>[typeof window.require,typeof window.process]),['undefined','undefined']);
  await assert.rejects(page.evaluate(()=>window.hackerTubeDesktop.api('https://example.com')));
  passed('Sandbox, isolated bridge and API origin validation');
  const id=await page.locator('.video-card').first().getAttribute('data-id');
  await page.locator('.video-card').first().locator('[data-save]').click();
  await page.waitForFunction(()=>document.querySelector('#later-count').textContent==='1');
  await page.locator('[data-page="later"]').click();
  assert.equal(await page.locator('.video-card').count(),1);
  await page.locator('.video-card .thumbnail').click();
  await page.locator('[data-like]').click();
  passed('Watch later, library navigation and likes work offline');
  await app.evaluate(({shell,app})=>{app.testOpened=[];shell.openExternal=async url=>{app.testOpened.push(url);};});
  await page.locator('[data-watch]').click();
  assert.deepEqual(await app.evaluate(({app})=>app.testOpened),['https://www.youtube.com/watch?v='+id]);
  await page.evaluate(()=>window.open('file:///etc/passwd'));
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().length),1);
  passed('Video playback opens only validated URLs in system browser');
  await page.locator('#detail .close').click();
  await page.locator('#settings').click();
  const backup=join(temp,'backup.json');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backup);
  await page.locator('#export').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('备份已导出'));
  assert.deepEqual(JSON.parse(await readFile(backup,'utf8')).later,[id]);
  const incoming=freshState();incoming.later=[id==='SxdOUGdseq4'?'8pTEmbeENF4':'SxdOUGdseq4'];await writeFile(backup,JSON.stringify(incoming));
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},backup);
  await page.locator('#import').click();
  await page.waitForFunction(()=>document.querySelector('#later-count').textContent==='2');
  await writeFile(backup,'{broken');await page.locator('#import').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('导入失败'));
  assert.equal(await page.locator('#later-count').innerText(),'2');
  passed('Native file backup exports, merges browser-format state and rejects invalid files');
  await page.locator('#settings-dialog .close').click();
  await page.locator('#theme').click();
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
  await app.close();app=null;
  page=await launch();
  assert.equal(await page.locator('#later-count').innerText(),'2');
  assert.equal(await page.locator('#liked-count').innerText(),'1');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  passed('Favorites, history and theme survive application restart');
  await page.locator('#theme').click();
  await page.locator('#search').fill('computer');
  await page.waitForFunction(()=>document.querySelector('#collection-title').textContent==='搜索：computer');
  assert.ok(await page.locator('.video-card').count()>0);
  passed('Local full-text search works with network disabled');
  await page.locator('#search').fill('');
  await page.waitForFunction(()=>document.querySelector('#collection-title').textContent==='今天，看看这些');
  await app.evaluate(({session})=>session.defaultSession.disableNetworkEmulation());
  await page.reload();
  await page.locator('.video-card').first().waitFor();
  await page.waitForFunction(()=>document.querySelector('.hero-picture img')?.complete,{},{timeout:20000}).catch(()=>{});
  await mkdir('docs/images',{recursive:true});
  await page.screenshot({path:'docs/images/desktop.png'});
  await mkdir('artifacts',{recursive:true});
  await writeFile('artifacts/desktop-test.json',JSON.stringify({runtime:process.env.HACKERTUBE_TEST_EXECUTABLE?'packaged':'development',passed:results},null,2));
  console.log(`Desktop smoke test: ${results.length} checks passed.`);
} finally {if(app)await app.close();await rm(temp,{recursive:true,force:true});}
